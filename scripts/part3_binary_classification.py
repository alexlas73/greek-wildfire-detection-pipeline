# Custom Metrics with F2-Score Function
""" Calculates evaluation metrics (Precision, Recall, F1, F2) during training """
def compute_metrics(eval_pred):
    logits, labels = eval_pred
    predictions = np.argmax(logits, axis=-1)

    precision, recall, f1, _ = precision_recall_fscore_support(labels, predictions, average='binary')
    f2 = fbeta_score(labels, predictions, beta=2.0, average='binary')

    return {
        'precision': precision,
        'recall': recall,
        'f1': f1,
        'f2': f2
    }

# Evaluation Report Function
""" Αutomates the generation of the Confusion Matrix and Classification Report for each model """
def print_evaluation_report(y_true, y_pred, model_name):
    print(f"\n==================================================")
    print(f" Model Evaluation: {model_name}")
    print(f"==================================================")

    # Confusion Matrix
    cm = confusion_matrix(y_true, y_pred)
    cm_df = pd.DataFrame(cm,
                         index=['Actual: Non-Fire (0)', 'Actual: Fire (1)'],
                         columns=['Predicted: Non-Fire (0)', 'Predicted: Fire (1)'])
    print("\nConfusion Matrix:")
    print(cm_df)

    # Classification Report
    print("\nClassification Report:")
    print(classification_report(y_true, y_pred))

    # Metrics
    precision, recall, f1, _ = precision_recall_fscore_support(y_true, y_pred, average='binary')
    f2 = fbeta_score(y_true, y_pred, beta=2.0, average='binary')

    print(f"\nMetrics for {model_name}:")
    print(f"Precision: {precision:.4f} | Recall: {recall:.4f} | F1: {f1:.4f} | F2: {f2:.4f}")

def plot_training_history(trainer, model_name):
    """
    Extracts and plots the Loss (Training vs Validation) curves
    from the history of a Hugging Face Trainer.
    """
    print(f"\n--- Extracting model Loss Curves: {model_name} ---")

    history = trainer.state.log_history

    # Lists for data keeping
    train_loss = []
    eval_loss = []
    epochs = []

    # Search history to collect metrics for each epoch
    for entry in history:
        # If the record concerns Validation (has eval_loss)
        if 'eval_loss' in entry:
            eval_loss.append(entry['eval_loss'])
            epochs.append(entry['epoch'])
        # If the record concerns Training (has a loss)
        elif 'loss' in entry:
            train_loss.append(entry['loss'])

    # Check if there are enough data for the graph
    if not train_loss or not eval_loss:
        print("[ERROR]: Not enough loss data found in Trainer history.")
        return

    # Synchronization of list lengths (in case logs differ)
    min_length = min(len(train_loss), len(eval_loss))
    train_loss = train_loss[:min_length]
    eval_loss = eval_loss[:min_length]
    epochs = epochs[:min_length]

    # Graph Design
    plt.figure(figsize=(10, 6))
    plt.plot(epochs, train_loss, label='Training Loss', color='blue', marker='o', linewidth=2)
    plt.plot(epochs, eval_loss, label='Validation Loss', color='red', marker='x', linewidth=2)

    plt.title(f'Training vs Validation Loss - {model_name}', fontsize=14)
    plt.xlabel('Epochs', fontsize=12)
    plt.ylabel('Loss (Σφάλμα)', fontsize=12)
    plt.legend(fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.7)

    plt.show()

def perform_error_analysis(texts, y_true, y_pred, model_name):
    """
    Model Error Analysis Function:
    Identifies & categorizes misclassifications to an Excel file (with a primary focus on False Negatives),
    enabling an in-depth analysis of the errors occured
    """
    print(f"\n--- Starting {model_name} Error Analysis ---")

    # DataFrame Creation
    analysis_df = pd.DataFrame({
        f'Text Input': texts,
        'True Label': y_true,
        f'Prediction': y_pred
    })

    # We keep ONLY the errors (True Label vs Prediction)
    errors_df = analysis_df[analysis_df['True Label'] != analysis_df['Prediction']].copy()

    # Error Categorization
    # We pay special attention to False Negatives (Missed Fires)
    def categorize_error(row):
        if row['True Label'] == 0 and row['Prediction'] == 1:
            return 'False Positive (False Alarm)'
        elif row['True Label'] == 1 and row['Prediction'] == 0:
            return 'False Negative (Missed Fire)'
        return 'Unknown'

    errors_df['Error Type'] = errors_df.apply(categorize_error, axis=1)
    errors_df = errors_df.sort_values(by='Error Type')

    # Print False Negatives
    false_negatives = errors_df[errors_df['Error Type'] == 'False Negative (Missed Fire)']

    print(f"\n" + "="*70)
    print(f"Caution: {len(false_negatives)} False Negatives (Missed Fires) Found in {model_name}")
    print("="*70)

    for index, row in false_negatives.iterrows():
        print(f"-> {row['Text Input']}\n")

    print("="*70)

    # File Save and Download
    safe_model_name = model_name.replace('-', '_').replace(' ', '_')
    output_filename = f"{safe_model_name}_Error_Analysis.xlsx"

    errors_df.to_excel(output_filename, index=False)

    print(f"\nAnalysis complete! Found a total of {len(errors_df)} misclassified tweets.")
    print(f"You can download {output_filename} from the Colab's File section...")

