# 3b. SVM with TF-IDF & 5-Fold Cross Validation (Grid Search)
# We test Cross Validation (K-Fold) and Grid Search (hyperparameter tuning) for better results

print("\n--- Training model: SVM with K-Fold & Grid Search ---")

# We use the 'Hard Cleaned Text' for traditional ML models like SVM
X_svm = df['Hard Cleaned Text'].values
y_svm = df['is_fire'].values

# 1st Split: 70% for Training and 30% temporal
X_train_svm, X_temp_svm, y_train_svm, y_temp_svm = train_test_split(
    X_svm, y_svm, test_size=0.30, random_state=42, stratify=y_svm
)

# 2nd Split: Cut 30% in half -> 15% Val, 15% Test
X_val_svm, X_test_svm, y_val_svm, y_test_svm = train_test_split(
    X_temp_svm, y_temp_svm, test_size=0.50, random_state=42, stratify=y_temp_svm
)

# Pipeline
# During the K-Fold CV, the TF-IDF vocabulary should be built on the training (K-1) folds.
# That way data leakage from the (K) validation fold is prevented.
pipeline = Pipeline([
    ('tfidf', TfidfVectorizer(ngram_range=(1, 2))),
    ('svm', SVC(kernel='linear', class_weight='balanced', random_state=42))
])

# Parameter selection for Grid Search

# max_features is the total size of the vocabulary selected
# We test: 5000, 10000
# C controls the trade-off between a wider margin (low C) and correctly classifying all points (high C).
# We test: 0.1, 1, 5, 10, 50
# Total of 2x5=10 models to be tested. Each one 5 times (5-Fold)

param_grid = {
    'tfidf__max_features': [5000, 10000],
    'svm__C': [0.1, 1, 5, 10, 50]
}

# Grid Search
# fbeta_score calculates custom F_scores (we want F2-score which is beta=2.0)
f2_scorer = make_scorer(fbeta_score, beta=2.0)

# We select to search for the best F2-score by using a 5-fold CV
# n_jobs=-1 utilizes all available CPU cores
grid_search = GridSearchCV(pipeline, param_grid, cv=5, scoring=f2_scorer, n_jobs=-1, verbose=1)

print("Starting Grid Search...")
print("Optimization based on F2-Score...")
grid_search.fit(X_train_svm, y_train_svm)

# Winner model
print(f"\nBest hypermeter selection:")
print(grid_search.best_params_)

# Model Prediction based on the locked Test Set (20%)
# grid_search uses the winner model for the prediction
y_pred_best = grid_search.predict(X_test_svm)

# Model Evaluation (Advanced SVM)
print_evaluation_report(y_test_svm, y_pred_best, "Advanced SVM (K-Fold & GridSearch)")

print("\nSVM with K-Fold & Grid Search execution complete!")

# 4a. Training Model: GreekBERT

print("\n--- Training Model: GreekBERT ---")

# Definition of the pre-trained GreekBERT model
model_name = "nlpaueb/bert-base-greek-uncased-v1"

# Load Tokenizer
tokenizer_bert = AutoTokenizer.from_pretrained(model_name)

# We use the 'Advanced Cleaned Text' for uncased Transformer models
X_bert = df['Advanced Cleaned Text'].tolist()
y_bert = df['is_fire'].tolist()

# 1st Split: Keep 30% for Val & Test - Train is assigned 70%.
X_train_b, X_temp, y_train_b, y_temp = train_test_split(
    X_bert, y_bert, test_size=0.30, random_state=42, stratify=y_bert
)

# 2nd Split: Cut X_temp in half to take 15% Val και 15% Test
X_val_b, X_test_b, y_val_b, y_test_b = train_test_split(
    X_temp, y_temp, test_size=0.50, random_state=42, stratify=y_temp
)

# Tokenization function
def tokenize_function(examples):
    return tokenizer_bert(examples['text'], padding="max_length", truncation=True, max_length=128)

train_dataset = Dataset.from_dict({'text': X_train_b, 'label': y_train_b})
val_dataset = Dataset.from_dict({'text': X_val_b, 'label': y_val_b})
test_dataset = Dataset.from_dict({'text': X_test_b, 'label': y_test_b})

train_dataset = train_dataset.map(tokenize_function, batched=True)
val_dataset = val_dataset.map(tokenize_function, batched=True)
test_dataset = test_dataset.map(tokenize_function, batched=True)

# Load Model for Sequence Classification (Binary: num_labels=2)
model = AutoModelForSequenceClassification.from_pretrained(model_name, num_labels=2)

# Definition of Training Arguments
# Hyperparameter Tuning: Epochs, batch size, and learning rate can be tuned for better results
training_args = TrainingArguments(
    output_dir='./results',
    hub_model_id="mariossmrs/greek-bert-fire-detection-binary-classification",
    num_train_epochs=4, # Tuning
    per_device_train_batch_size=16, # Tuning
    per_device_eval_batch_size=32, # Tuning
    learning_rate=5e-6, # Tuning
    weight_decay=0.1, # Tuning - INCREASE: Greater penalty for memorization
    warmup_ratio=0.1, # Tuning - The first 10% of steps are a gradual "warm-up"
    eval_strategy="epoch",
    save_strategy="epoch",
    load_best_model_at_end=True,
    metric_for_best_model="f2",      # Uses "F2-Score" to optimize the training
    greater_is_better=True,          # Greater F2-Score is better
    fp16=True,                      #  GPU acceleration - turn to True when training the big dataset
    report_to="none",
    logging_dir='./logs',
    logging_strategy="epoch" # for 'no log' error
)

# Initialize Trainer
trainer_bert = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=val_dataset,
    compute_metrics=compute_metrics
)

# Model Training
print("Starting BERT fine-tuning...")
trainer_bert.train()

# Predictions Extraction
