def run_inference(df, model_path, threshold=0.30):
    """
    Performs inference using the fine-tuned model stored in Hugging Face.
    Includes custom thresholding and logs fire probabilities.

    About the threshold (0.30):
    In emergency response contexts, minimizing False Negatives (missed events)
    is far more critical than minimizing False Positives (false alarms).
    By lowering the decision threshold from the default 0.50 to 0.30, we intentionally
    prioritize Recall over Precision. This ensures that posts with even a moderate
    probability of reporting an active fire are flagged for downstream spatial processing.
    """
    print(f"\nLoading trained GreekBERT from Hugging Face: {model_path}...")

    # 1. Load Tokenizer and Model from the Drive path
    tokenizer = AutoTokenizer.from_pretrained(model_path)
    model = AutoModelForSequenceClassification.from_pretrained(model_path)

    # 2. Prepare data (GreekBERT requires 'Advanced Cleaned Text')
    texts = df['Advanced Cleaned Text'].tolist()

    def tokenize_function(examples):
        return tokenizer(examples['text'], padding="max_length", truncation=True, max_length=128)

    dataset = Dataset.from_dict({'text': texts})
    dataset = dataset.map(tokenize_function, batched=True)

    # 3. Execution
    print("Executing predictions...")
    trainer = Trainer(model=model)
    raw_predictions, _, _ = trainer.predict(dataset)

    # Convert logits to probabilities
    logits_tensor = torch.tensor(raw_predictions)
    probabilities = torch.softmax(logits_tensor, dim=-1).numpy()
    fire_probs = probabilities[:, 1] # Probability for Class 1 (Fire)

    # Apply custom threshold
    predictions = (fire_probs >= threshold).astype(int)

    # Log results back to DataFrame
    df['Fire Probability'] = np.round(fire_probs, 3)
    df['Predicted Label'] = predictions

    fires_found = sum(predictions == 1)
    print(f"\nInference complete!\nTotal Dataset: {len(predictions)} Tweets\nPredicted as Fire-Related:{fires_found} Tweets")

    return df

