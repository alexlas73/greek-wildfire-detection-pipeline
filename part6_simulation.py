# CELL 4b: Model Inference (RoBERTa) - Multilabel Classification
# ====================================================================================

def run_multilabel_inference(df, model_path, threshold_forest=0.5, threshold_urban=0.5):
    """
    Performs multilabel inference ONLY on tweets predicted as fire-related.
    """
    print(f"\n--- Loading Multilabel Model from Hugging Face: {model_path} ---")

    # 1. Filter dataset: Keep only tweets predicted as fire
    df_fire = df[df['Predicted Label'] == 1].copy()

    if df_fire.empty:
        print("[INFO] No fire-related tweets found to classify further.")
        # Default initialization if nothing found
        df['is_wildland_pred'] = 0
        df['is_urban_pred'] = 0
        return df

    # 2. Load Tokenizer and Model
    tokenizer = AutoTokenizer.from_pretrained(model_path)
    model = AutoModelForSequenceClassification.from_pretrained(model_path)

    # 3. Prepare data (use the same text column you trained the multilabel model on)
    texts = df_fire['Light Cleaned Text'].astype(str).tolist() # Assuming XLM-RoBERTa won - change to 'Advanced Cleaned' if GreekBERT won

    def tokenize_function(examples):
        return tokenizer(examples['text'], padding="max_length", truncation=True, max_length=128)

    dataset = Dataset.from_dict({'text': texts})
    dataset = dataset.map(tokenize_function, batched=True)

    # 4. Predict
    print("Executing Multilabel predictions...")
    trainer = Trainer(model=model)
    raw_predictions, _, _ = trainer.predict(dataset)

    # Convert logits to probabilities (Sigmoid)
    probabilities = torch.sigmoid(torch.tensor(raw_predictions)).numpy()

    # Apply thresholds independently
    is_wildland_pred = (probabilities[:, 0] > threshold_forest).astype(int)
    is_urban_pred = (probabilities[:, 1] > threshold_urban).astype(int)

    # 5. Merge results back to the original DataFrame
    # 5. Merge results back to the original DataFrame
    # Create columns initialized to 0
    df['is_wildland_pred'] = 0
    df['is_urban_pred'] = 0

    # Update the rows that were predicted as fire
    df.loc[df['Predicted Label'] == 1, 'is_wildland_pred'] = is_wildland_pred
    df.loc[df['Predicted Label'] == 1, 'is_urban_pred'] = is_urban_pred

    df_results = df[df['Predicted Label'] == 1]
    total_fires = len(df_results)

    forest_only = len(df_results[(df_results['is_wildland_pred'] == 1) & (df_results['is_urban_pred'] == 0)])
    urban_only = len(df_results[(df_results['is_wildland_pred'] == 0) & (df_results['is_urban_pred'] == 1)])
    mixed_fire = len(df_results[(df_results['is_wildland_pred'] == 1) & (df_results['is_urban_pred'] == 1)])
    unidentified = len(df_results[(df_results['is_wildland_pred'] == 0) & (df_results['is_urban_pred'] == 0)])

    print("\nMultilabel inference complete!\n")
    print(f"Total Fire-Related Tweets Analyzed: {total_fires}")
    print("--------------------------------------------------")
    print(f"Forest Fires:                       {forest_only}")
    print(f"Urban Fires:                        {urban_only}")
    print(f"Mixed Fires (Wildland-Urban):       {mixed_fire}")
    print(f"Unidentified Fire Type:             {unidentified}")
    print("--------------------------------------------------")

    return df

